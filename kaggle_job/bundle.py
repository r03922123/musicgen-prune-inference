"""Embed source files into a Kaggle job's run.py (Kaggle script kernels upload one file).

  python kaggle_job/bundle.py                  # all jobs
  python kaggle_job/bundle.py kaggle_corpus    # one job
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# job dir -> {name in SOURCES: repo path}
JOBS = {
    "kaggle_job": {"prune.py": "torch/prune.py", "bench.py": "torch/bench.py"},
    "kaggle_corpus": {p: p for p in ("torch/prune.py", "torch/scorers.py", "torch/generate_corpus.py",
                                     "torch/score_cmi.py",
                                     "data/prompts/musiccaps_40.tsv", "data/prompts/redteam_10.tsv")},
}
MARK = "# --- bundled sources: generated by kaggle_job/bundle.py, do not edit below ---\n"

for job in sys.argv[1:] or JOBS:
    run = ROOT / job / "run.py"
    head = run.read_text().split(MARK)[0]
    src = {name: (ROOT / path).read_text() for name, path in JOBS[job].items()}
    run.write_text(head + MARK + f"SOURCES = {src!r}\n\nif __name__ == \"__main__\":\n    main()\n")
    print(f"bundled {list(src)} into {run}")
