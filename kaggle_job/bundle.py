"""Embed torch/prune.py and torch/bench.py into kaggle_job/run.py (Kaggle uploads one file)."""
from pathlib import Path

root = Path(__file__).resolve().parent
run = root / "run.py"
MARK = "# --- bundled sources: generated by kaggle_job/bundle.py, do not edit below ---\n"
head = run.read_text().split(MARK)[0]
src = {n: (root.parent / "torch" / n).read_text() for n in ("prune.py", "bench.py")}
run.write_text(head + MARK + f"SOURCES = {src!r}\n\nif __name__ == \"__main__\":\n    main()\n")
print(f"bundled {list(src)} into {run}")
